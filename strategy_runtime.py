"""
Runtime support for code generated by the score-code generator: the indicator math
(`relative_strength_index`, `cumulative_return`, ...) and weight-combination helpers
that generated `_node_*` functions call into. Kept separate from the code generator
itself so the generated Python only has one small, readable import to depend on.

A price series is just `Sequence[float]`, chronological ascending (oldest first,
most recent/current last) -- e.g. daily closes. Every indicator function reads
backwards from the end of the series, consistent with how the strategy is evaluated
"as of today" using a trailing window.

Every name in INDICATOR_FUNCTIONS below is confirmed against 3 real strategies pulled
from a live account (not guessed) -- see the code generator's module docstring for how
and what's still unconfirmed (mainly: step/fn types those 3 strategies happen not to
use). Simple-average conventions, not Wilder-smoothed:
`relative_strength_index()` here averages gains/losses evenly over the window rather
than using Wilder's exponential smoothing, matching the same simplification
`ibkr_client.get_atr()` already makes for ATR elsewhere in this project (see that
function's docstring). The strategy's own engine may compute these indicators slightly
differently -- treat this as a reasonable approximation to sanity-check logic with, not
a bit-for-bit reproduction of the source backtester.
"""

# Deliberately not `from typing import Tuple`: QuantConnect Cloud's Python environment
# (used by the generated code when backtested via Lean) resolves a
# bare `Tuple` to .NET's System.Tuple via its interop stubs, colliding with typing's.
# `tuple[...]` (lowercase, PEP 585) is used in annotations below instead -- safe on any
# Python version because of `from __future__ import annotations` above.


def _window(prices: Sequence[float], window_days: int, extra: int = 0) -> Sequence[float]:
    """The trailing `window_days + extra` prices. `extra` is 1 for indicators that need
    one extra leading data point to compute `window_days` worth of day-over-day change
    (returns, RSI, drawdown)."""
    n = window_days + extra
    if len(prices) < n:
        raise ValueError(f"Need at least {n} price points for a {window_days}-day window, got {len(prices)}.")
    return prices[-n:]


def current_price(prices: Sequence[float], window_days: Optional[int] = None) -> float:
    """`window_days` accepted (and ignored) so every indicator function has the same
    `(prices, window_days)` signature -- simplifies the code generator's call sites."""
    if not prices:
        raise ValueError("Empty price series.")
    return float(prices[-1])


def cumulative_return(prices: Sequence[float], window_days: int) -> float:
    """Percent change from `window_days` ago to the most recent price."""
    w = _window(prices, window_days, extra=1)
    start, end = w[0], w[-1]
    return (end / start - 1.0) * 100.0


def moving_average_price(prices: Sequence[float], window_days: int) -> float:
    return statistics.fmean(_window(prices, window_days))


def moving_average_return(prices: Sequence[float], window_days: int) -> float:
    """Mean of day-over-day percent returns over the trailing window."""
    w = _window(prices, window_days, extra=1)
    returns = [(w[i] / w[i - 1] - 1.0) * 100.0 for i in range(1, len(w))]
    return statistics.fmean(returns)


def exponential_moving_average_price(prices: Sequence[float], window_days: int) -> float:
    """Standard EMA (alpha = 2/(window_days+1)), seeded with the simple average of the
    earliest `window_days` points then applied forward over whatever history is given
    (not just the trailing window -- EMA is defined recursively over the whole series)."""
    if len(prices) < window_days:
        raise ValueError(f"Need at least {window_days} price points, got {len(prices)}.")
    alpha = 2.0 / (window_days + 1)
    ema = statistics.fmean(prices[:window_days])
    for p in prices[window_days:]:
        ema = alpha * p + (1 - alpha) * ema
    return ema


def standard_deviation_price(prices: Sequence[float], window_days: int) -> float:
    return statistics.pstdev(_window(prices, window_days))


def standard_deviation_return(prices: Sequence[float], window_days: int) -> float:
    w = _window(prices, window_days, extra=1)
    returns = [(w[i] / w[i - 1] - 1.0) * 100.0 for i in range(1, len(w))]
    return statistics.pstdev(returns)


def relative_strength_index(prices: Sequence[float], window_days: int) -> float:
    """Relative Strength Index, 0-100. Simple (not Wilder-smoothed) average of
    gains/losses over the window -- see module docstring."""
    w = _window(prices, window_days, extra=1)
    changes = [w[i] - w[i - 1] for i in range(1, len(w))]
    gains = [c for c in changes if c > 0]
    losses = [-c for c in changes if c < 0]
    avg_gain = sum(gains) / window_days
    avg_loss = sum(losses) / window_days
    if avg_loss == 0:
        return 100.0 if avg_gain > 0 else 50.0
    rs = avg_gain / avg_loss
    return 100.0 - 100.0 / (1.0 + rs)


def max_drawdown(prices: Sequence[float], window_days: int) -> float:
    """Largest peak-to-trough decline over the trailing window, as a positive percent
    (e.g. 12.5 for a 12.5% drawdown)."""
    w = _window(prices, window_days, extra=1)
    peak = w[0]
    worst = 0.0
    for p in w:
        peak = max(peak, p)
        worst = max(worst, (peak - p) / peak)
    return worst * 100.0


