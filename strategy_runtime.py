def combine_equal(parts: List[Dict[str, float]]) -> Dict[str, float]:
    """Equal-weight combination of sibling subtrees' {ticker: weight} results (each
    summing to ~1.0 on its own) into one {ticker: weight} dict for their shared parent,
    also summing to ~1.0."""
    if not parts:
        return {}
    share = 1.0 / len(parts)
    result: Dict[str, float] = {}
    for part in parts:
        for ticker, weight in part.items():
            result[ticker] = result.get(ticker, 0.0) + weight * share
    return result


def combine_weighted(parts: List[tuple[float, Dict[str, float]]]) -> Dict[str, float]:
    """Like combine_equal(), but each (fraction, {ticker: weight}) pair carries its own
    explicit share (the source's per-child `weight: {num, den}`) instead of an equal 1/n."""
    result: Dict[str, float] = {}
    for fraction, part in parts:
        for ticker, weight in part.items():
            result[ticker] = result.get(ticker, 0.0) + weight * fraction
    return result


def combine_inverse_vol(parts: List[tuple[float, Dict[str, float]]]) -> Dict[str, float]:
    """Inverse-volatility weighting: each (volatility, {ticker: weight}) pair gets a
    share proportional to 1/volatility (higher volatility -> smaller share), normalized
    so shares sum to 1.0. `volatility` is typically standard_deviation_return() computed
    by the generated code for that child over the configured window.

    Approximation, not a confirmed reproduction of the source's own inverse-vol formula
    (e.g. the exact window/lookback used internally is not publicly documented
    as of when this was written) -- treat results as directional, verify against a real
    backtest before trusting exact weights.

    A zero (or negative, shouldn't happen) volatility is floored to a tiny epsilon
    rather than treated as literal infinity or as zero weight -- 1/vol is undefined at
    vol=0, but the *intent* of inverse-vol weighting is "the calmer the asset, the more
    weight it gets", so a perfectly flat price series should end up dominant, not
    excluded."""
    epsilon = 1e-9
    inv = [(1.0 / max(vol, epsilon), part) for vol, part in parts]
    total = sum(w for w, _ in inv)
    if total <= 0:
        return combine_equal([part for _, part in parts])
    result: Dict[str, float] = {}
    for weight, part in inv:
        fraction = weight / total
        for ticker, w in part.items():
            result[ticker] = result.get(ticker, 0.0) + w * fraction
    return result


def select_filter(
    scored: List[tuple[float, Dict[str, float]]], select_fn: str, n: int
) -> Dict[str, float]:
    """The source's 'filter' step: rank candidates by a score (each generated by the
    strategy's configured sort-by-fn/sort-by-fn-params, e.g. cumulative_return over some
    window -- on either a single asset's own price series, or, for a candidate that's a
    whole subtree, a synthetic_price_series() built from its resulting weights) and keep
    only the top or bottom `n`, equal-weighted. select-fn/select-n/sort-by-fn field names
    confirmed from 3 real strategies, but the exact weighting applied among
    multiple *selected* candidates when n > 1 is not separately confirmed; equal-weight
    is the standard convention and what's assumed here."""
    if select_fn == "top":
        ranked = sorted(scored, key=lambda pair: pair[0], reverse=True)
    elif select_fn == "bottom":
        ranked = sorted(scored, key=lambda pair: pair[0])
    else:
        raise ValueError(f"Unknown select-fn {select_fn!r} (expected 'top' or 'bottom').")
    chosen = [part for _, part in ranked[:n]]
    return combine_equal(chosen)


def synthetic_price_series(weights: Dict[str, float], prices: Dict[str, Sequence[float]]) -> List[float]:
    """Builds a synthetic blended price series for a sub-portfolio: each underlying
    ticker's price series is normalized to start at 1.0 over the shared trailing window
    (so different price scales don't distort the blend), then combined according to
    `weights` (e.g. a generated `_node_*` function's {ticker: weight} result, summing to
    ~1.0) into one NAV-style series.

    Used to rank or measure the volatility of a filter/wt-inverse-vol *candidate* that's
    a whole subtree rather than a single asset, confirmed to occur in real strategies
    (a 'filter' whose children are themselves conditional sub-strategies, not plain
    tickers). The source's own exact method for this isn't confirmed -- this is a
    standard, reasonable approximation (a weighted index of normalized prices), not a
    verified reproduction of its internal formula."""
    tickers = [t for t in weights if weights[t] != 0]
    if not tickers:
        raise ValueError("No non-zero-weight tickers to blend into a synthetic series.")
    length = min(len(prices[t]) for t in tickers)
    if length == 0:
        raise ValueError("No overlapping price history among the weighted tickers.")
    normalized = {t: [p / prices[t][-length] for p in prices[t][-length:]] for t in tickers}
    return [sum(weights[t] * normalized[t][i] for t in tickers) for i in range(length)]


NODE_REGISTRY: Dict[str, Callable[[Dict[str, Sequence[float]]], Dict[str, float]]] = {}
"""Populated by generated `_node_*` functions (see the code generator) as each one is
defined, so nodes can call each other via call_node() by name rather than by bare Python
reference. Needed because a large strategy's generated code can be split across multiple
files (some hosting platforms, notably QuantConnect Cloud, cap individual file size at
64,000 characters -- easily exceeded; a complex real strategy can generate 800,000+
characters of Python), and a plain function can only resolve a bare-name call to another
function defined in its own module, not a sibling file's -- a shared registry sidesteps
that entirely, at the cost of one dict lookup per node evaluated."""


def call_node(name: str, prices: Dict[str, Sequence[float]]) -> Dict[str, float]:
    fn = NODE_REGISTRY.get(name)
    if fn is None:
        raise KeyError(
            f"Node function {name!r} was called but never registered in NODE_REGISTRY -- "
            "its defining module wasn't imported before this call. For a multi-file "
            "generated strategy (see generate_python_chunks()), make "
            "sure every chunk module gets imported (even just for its registration side "
            "effect) before run_strategy() is called."
        )
    return fn(prices)
